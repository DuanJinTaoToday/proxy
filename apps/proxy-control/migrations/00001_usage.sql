CREATE TABLE traffic_grants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    tenant_id text NOT NULL,
    granted_bytes bigint NOT NULL CHECK (granted_bytes >= 0),
    used_bytes bigint NOT NULL DEFAULT 0 CHECK (used_bytes >= 0 AND used_bytes <= granted_bytes),
    overdraft_offset_bytes bigint NOT NULL DEFAULT 0 CHECK (overdraft_offset_bytes >= 0 AND overdraft_offset_bytes <= used_bytes),
    starts_at timestamptz NOT NULL,
    expires_at timestamptz CHECK (expires_at > starts_at),
    activated_at timestamptz,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
    source text NOT NULL CHECK (source IN ('recharge', 'adjustment')),
    created_by text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX traffic_grants_tenant_expiry ON traffic_grants (tenant_id, expires_at);

CREATE TABLE balance_ledger (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL,
    kind text NOT NULL CHECK (kind IN ('recharge', 'adjust_add', 'adjust_subtract', 'overdraft_offset', 'grant_expire', 'grant_expire_correction')),
    grant_id bigint REFERENCES traffic_grants(id),
    delta_bytes bigint NOT NULL,
    available_before bigint NOT NULL,
    available_after bigint NOT NULL,
    external_ref text,
    reason text NOT NULL DEFAULT '',
    operator text NOT NULL,
    created_at timestamptz NOT NULL,
    correction_of bigint REFERENCES balance_ledger(id),
    UNIQUE (tenant_id, external_ref)
);
CREATE UNIQUE INDEX balance_ledger_one_expiry ON balance_ledger (grant_id) WHERE kind = 'grant_expire';

