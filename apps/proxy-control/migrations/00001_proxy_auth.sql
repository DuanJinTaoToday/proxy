CREATE TABLE gateways (
    id text PRIMARY KEY,
    name text NOT NULL,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    disabled_at timestamptz
);

CREATE TABLE gateway_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gateway_id text NOT NULL REFERENCES gateways(id),
    scope text NOT NULL CHECK (scope IN ('report', 'auth')),
    token_hash bytea NOT NULL UNIQUE CHECK (octet_length(token_hash) = 32),
    created_at timestamptz NOT NULL DEFAULT now(),
    rotation_slot smallint NOT NULL DEFAULT 1 CHECK (rotation_slot IN (1, 2)),
    revoked_at timestamptz
);

CREATE UNIQUE INDEX gateway_tokens_active_slot ON gateway_tokens (gateway_id, scope, rotation_slot)
