import { test, expect } from '@playwright/test'

async function signIn(page, location = '/console') {
  await page.goto(location)
  await page.getByLabel('手机号', { exact: true }).fill('13800000001')
  await page.getByLabel('密码', { exact: true }).fill('proxy-local-test')
  await page.getByRole('button', { name: '登录', exact: true }).click()
}

async function screenshot(page, info, name) {
  const path = info.outputPath(name + '.png')
  await page.screenshot({ path, fullPage: true })
  await info.attach(name, { path, contentType: 'image/png' })
}

test('租户侧栏按产品和管理分组，保留原业务入口', async ({ page }, info) => {
  await signIn(page)
  const nav = page.getByRole('navigation', { name: '租户导航' })
  const link = name => nav.getByRole('link', { name, exact: true })
  const button = name => nav.getByRole('button', { name, exact: true })
  const heading = name => page.getByRole('heading', { name, level: 1, exact: true })
  const toggle = page.getByRole('button', { name: '切换侧栏' })
  const dynamic = button('动态住宅代理-GB')
  const staticIP = button('静态住宅代理-IP')

  await expect(heading('仪表板')).toBeVisible()
  await expect(page.getByRole('heading', { name: '快捷操作' })).toBeVisible()
  await expect(nav.getByText('代理', { exact: true })).toBeVisible()
  await expect(nav.getByText('管理', { exact: true })).toBeVisible()
  await expect(nav.getByRole('link').or(nav.getByRole('button'))).toHaveText([
    '仪表板', '动态住宅代理-GB', '静态住宅代理-IP', '子账户', '鲲星钱包', '我的账户',
  ])
  await expect(link('仪表板')).toHaveAttribute('aria-current', 'page')
  await screenshot(page, info, 'desktop-sidebar')

  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await dynamic.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(dynamic).toHaveAttribute('aria-expanded', 'true')
  await expect(link('流量套餐')).toHaveCount(0)
  await expect(link('SOCKS5 接入说明')).toHaveAttribute('href', '/#socks5')
  await link('日用量').click()
  await expect(heading('日用量')).toBeVisible()
  await Promise.all([page.waitForResponse('**/public/products'), page.reload()])
  await expect(dynamic).toHaveAttribute('aria-expanded', 'true')
  await expect(link('日用量')).toHaveAttribute('aria-current', 'page')

  await staticIP.click()
  await expect(link('购买静态 IP')).toHaveCount(0)
  await link('我的 IP').click()
  await expect(heading('我的 IP')).toBeVisible()
  await expect(link('我的 IP')).toHaveAttribute('aria-current', 'page')
  await link('子账户').click()
  await expect(heading('子账户')).toBeVisible()
  await expect(page.getByRole('button', { name: '创建子账号' })).toBeEnabled()
  await link('鲲星钱包').click()
  await expect(heading('鲲星钱包')).toBeVisible()
  await expect(page.getByRole('tab', { name: '钱包流水' })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: '订单记录' }).click()
  await expect(page.getByRole('tab', { name: '订单记录' })).toHaveAttribute('aria-selected', 'true')
  await expect(link('鲲星钱包')).toHaveAttribute('aria-current', 'page')

  await link('我的账户').click()
  await expect(heading('我的账户')).toBeVisible()
  const main = page.getByRole('main')
  await expect(main.getByText('13800000001', { exact: true })).toBeVisible()
  await expect(main.getByText('Alpha', { exact: true })).toBeVisible()
  await expect(main.getByText('localalpha', { exact: true })).toBeVisible()
  await screenshot(page, info, 'desktop-account')

  await page.evaluate(() => sessionStorage.removeItem('proxy-console.login-phone'))
  await page.reload()
  await expect(heading('我的账户')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Alpha', exact: true })).toBeVisible()
  await expect(main.getByText('重新登录后可查看', { exact: true })).toBeVisible()
})

test('窄屏展开代理分组，进入页面后关闭侧栏', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signIn(page)
  const toggle = page.getByRole('button', { name: '切换侧栏' })
  const nav = page.getByRole('navigation', { name: '租户导航' })
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await toggle.click()
  const staticIP = nav.getByRole('button', { name: '静态住宅代理-IP', exact: true })
  await staticIP.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(staticIP).toHaveAttribute('aria-expanded', 'true')
  await screenshot(page, info, 'mobile-sidebar')
  await nav.getByRole('link', { name: '我的 IP', exact: true }).click()
  await expect(page.getByRole('heading', { name: '我的 IP', level: 1 })).toBeVisible()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(nav).not.toBeVisible()
})
