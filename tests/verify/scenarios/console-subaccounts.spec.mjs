import { expect, test } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { screenshot, signInTenant } from '../support/console.mjs'

const createAction = page => page.getByRole('button', { name: '创建子账号', exact: true })
const rowFor = (page, name) => page.getByRole('row').filter({ has: page.getByText(name, { exact: true }) })

async function openCreate(page, name, password) {
  await createAction(page).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel(/子账号名/).fill(name)
  await dialog.getByLabel(/^\*?密码$/).fill(password)
  return dialog
}

async function submitCreate(dialog) {
  await dialog.getByRole('button', { name: '创建', exact: true }).click()
}

test('租户维护子账号账密、备注、状态和用量上限，刷新后保留结果', async ({ page, context }, info) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await signInTenant(page)
  await page.getByRole('menuitem', { name: '代理子账号', exact: true }).click()
  await expect(page.getByRole('heading', { name: '代理子账号', exact: true })).toBeVisible()
  await expect(page.getByText('0 / 10', { exact: true })).toBeVisible()

  let dialog = await openCreate(page, 'Shop01', '123456')
  await submitCreate(dialog)
  await expect(dialog.getByText(/使用 4–8 位/)).toHaveCount(2)
  await expect(dialog.getByText(/使用 6–12 位/)).toHaveCount(2)
  await dialog.getByLabel(/子账号名/).fill('shop01')
  await dialog.getByLabel(/^\*?密码$/).fill('Start123')
  await dialog.getByLabel('备注', { exact: true }).fill('站点采集')
  await dialog.getByRole('switch', { name: '累计用量上限' }).press('Enter')
  const createLimit = dialog.getByRole('textbox', { name: '上限（GB）' })
  await dialog.getByRole('button', { name: '调高用量上限' }).click()
  await expect(createLimit).toHaveValue('15')
  await dialog.getByRole('button', { name: '调低用量上限' }).click()
  await expect(createLimit).toHaveValue('10')
  await createLimit.fill('1.25')
  await submitCreate(dialog)
  await expect(dialog).toBeHidden()
  await expect(page.getByText('1 / 10', { exact: true })).toBeVisible()

  const row = rowFor(page, 'shop01')
  await row.getByRole('button', { name: '复制 SOCKS5 用户名 localalpha.shop01' }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('localalpha.shop01')
  await expect(row.getByText('站点采集', { exact: true })).toBeVisible()
  await expect(row.getByText('0 GB / 1.25 GB')).toBeVisible()
  const createdAt = await row.locator('time').getAttribute('datetime')
  expect(Date.parse(createdAt)).toBeGreaterThan(0)

  dialog = await openCreate(page, 'shop01', 'Start123')
  await submitCreate(dialog)
  await expect(dialog.getByText('该子账号名已存在。', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()

  await row.getByRole('button', { name: '显示密码' }).click()
  await expect(row.getByText('Start123', { exact: true })).toBeVisible()
  await row.getByRole('button', { name: '复制密码' }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('Start123')
  await row.getByRole('button', { name: '隐藏密码' }).click()
  await expect(row.getByText('Start123', { exact: true })).toBeHidden()
  await row.getByRole('button', { name: '修改密码', exact: true }).click()
  await dialog.getByLabel(/新密码/).fill('Next456')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await row.getByRole('button', { name: '复制密码' }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('Next456')
  await expect(row.getByText('Next456', { exact: true })).toBeHidden()

  await row.getByRole('button', { name: '编辑', exact: true }).click()
  await dialog.getByLabel('备注', { exact: true }).fill('库存项目')
  await dialog.getByRole('switch', { name: '状态', checked: true }).press('Enter')
  const limit = dialog.getByRole('textbox', { name: '上限（GB）' })
  await limit.fill('1')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.getByText('上限只能调高或取消。', { exact: true })).toBeVisible()
  await limit.fill('9223372036.854775807')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(row.getByText('0 GB / 9,223,372,036.854775807 GB')).toBeVisible()
  await expect(row.getByText('库存项目', { exact: true })).toBeVisible()
  await expect(row.getByRole('switch', { name: '启用 shop01' })).not.toBeChecked()
  await row.getByRole('switch', { name: '启用 shop01' }).press('Enter')
  await expect(row.getByRole('switch', { name: '禁用 shop01？' })).toBeChecked()
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  await expect(limit).toHaveValue('9223372036.854775807')
  await dialog.getByRole('switch', { name: '累计用量上限' }).press('Enter')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(row.getByText('0 GB / 不限')).toBeVisible()

  await row.getByRole('button', { name: '编辑', exact: true }).click()
  // Advance the isolated DB fixture while the edit dialog still has the old usage.
  execFileSync('docker', [
    'compose', '-p', 'proxy-verify-' + process.env.VERIFY_ID,
    'exec', '-T', 'db', 'psql', '-U', 'proxy', '-d', 'proxy', '-v', 'ON_ERROR_STOP=1', '-c',
    "UPDATE proxy_subaccounts SET used_bytes=2000000000 WHERE tenant_id='alpha' AND name='shop01'",
  ], { cwd: new URL('../../../', import.meta.url) })
  await dialog.getByRole('switch', { name: '累计用量上限' }).press('Enter')
  await limit.fill('1')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.getByText('上限不能低于已用量。', { exact: true })).toBeVisible()
  await limit.fill('2.5')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(row.getByText('2 GB / 2.5 GB')).toBeVisible()

  await row.getByRole('switch', { name: '禁用 shop01？' }).press('Enter')
  await expect(dialog.getByText(/已有连接会继续到正常结束/)).toBeVisible()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(row.getByRole('switch')).toBeChecked()
  await row.getByRole('switch', { name: '禁用 shop01？' }).press('Enter')
  await dialog.getByRole('button', { name: '禁用', exact: true }).click()
  await expect(row.getByRole('switch')).not.toBeChecked()
  await page.getByRole('combobox', { name: '按状态筛选' }).press('Enter')
  await page.getByRole('option', { name: '启用', exact: true }).click()
  await expect(row).toBeHidden()
  await page.getByRole('combobox', { name: '按状态筛选' }).press('Enter')
  await page.getByRole('option', { name: '禁用', exact: true }).click()
  await expect(row).toBeVisible()
  const search = page.getByRole('textbox', { name: '搜索子账号名或备注' })
  await search.fill('站点采集')
  await expect(row).toBeHidden()
  await search.fill('库存项目')
  await expect(row).toBeVisible()

  await page.reload()
  await expect(row.getByRole('switch', { name: '启用 shop01' })).not.toBeChecked()
  await expect(row.getByText('库存项目', { exact: true })).toBeVisible()
  await expect(row.getByText('2 GB / 2.5 GB')).toBeVisible()
  await expect(row.locator('time')).toHaveAttribute('datetime', createdAt)
  await row.getByRole('button', { name: '显示密码' }).click()
  await expect(row.getByText('Next456', { exact: true })).toBeVisible()
  await row.getByRole('button', { name: '隐藏密码' }).click()
  await row.getByRole('switch', { name: '启用 shop01' }).press('Enter')
  await expect(row.getByRole('switch', { name: '禁用 shop01？' })).toBeChecked()
  await expect(dialog).toBeHidden()
  await page.reload()
  await expect(row.getByRole('switch', { name: '禁用 shop01？' })).toBeChecked()
  await screenshot(page, info, 'subaccount-persisted')
})

test('禁用账号继续占用名额，达到 10 个后禁用创建', async ({ page }, info) => {
  await signInTenant(page, '13800000002')
  await page.goto('/console/sub-accounts')
  await expect(page.getByText('0 / 10', { exact: true })).toBeVisible()
  for (let i = 1; i <= 10; i++) {
    const dialog = await openCreate(page, 'slot' + i, 'Quota123')
    if (i === 1) await dialog.getByRole('switch', { name: '状态', checked: true }).press('Enter')
    await submitCreate(dialog)
    await expect(dialog).toBeHidden()
    await expect(page.getByText(i + ' / 10', { exact: true })).toBeVisible()
  }
  await page.reload()
  await expect(page.getByText('10 / 10', { exact: true })).toBeVisible()
  await expect(rowFor(page, 'slot1').getByRole('switch')).not.toBeChecked()
  await expect(createAction(page)).toBeDisabled()
  await createAction(page).locator('..').focus()
  await expect(page.getByRole('tooltip')).toContainText('已用完 10 个子账号名额。启用和禁用的账号都计入。')
  await screenshot(page, info, 'subaccount-quota-full')
})

test('子账号列表请求失败后可重试，窄屏表格不撑开页面', async ({ page }, info) => {
  await signInTenant(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/v1/tenant/subaccounts', route => route.abort(), { times: 1 })
  await page.goto('/console/sub-accounts')
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.getByRole('region', { name: '子账号列表' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await screenshot(page, info, 'subaccounts-mobile')
  await page.getByRole('button', { name: /^语言[:：]/ }).click()
  await page.getByRole('menuitem', { name: 'English', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Subaccount list' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Create subaccount', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
